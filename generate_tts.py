async def gen(dialect_idx: int, prefix: str, index: int, text: str) -> None:
    voice_config = VOICES[dialect_idx]
    voice = voice_config["A"] if index < 5 else voice_config["B"]
    out = os.path.join(OUT_DIR, f"{prefix}_{dialect_idx}_{index}.mp3")
    await edge_tts.Communicate(text, voice, rate="+10%").save(out)
    print(f"OK {prefix}_{dialect_idx}_{index}.mp3 [{voice}] {text}")

async def main() -> None:
    if not os.path.exists(OUT_DIR):
        os.makedirs(OUT_DIR)
        
    for dialect_idx, category_data in TEXT_DATA.items():
        for prefix, texts in category_data.items():
            for i, text in enumerate(texts):
                await gen(dialect_idx, prefix, i, text)

if __name__ == "__main__":
    asyncio.run(main())
